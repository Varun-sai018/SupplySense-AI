def get_forecast_summary_by_execution(
    execution_id: int,
    connection=None
) -> Dict[str, Any]:
    """
    Calculates summary aggregate statistics for an execution's forecasts.

    Args:
        execution_id: ID of the pipeline execution.
        connection: Optional open PyMySQL database connection.

    Returns:
        Dict with summary stats (total_forecasts, distinct_categories, min_week, max_week, avg_demand).
    """
    should_close = False
    if connection is None:
        connection = get_connection()
        should_close = True

    cursor = connection.cursor()
    try:
        cursor.execute("""
            SELECT COUNT(*) AS total_forecasts,
                   COUNT(DISTINCT product_category) AS distinct_categories,
                   MIN(forecast_week) AS min_week,
                   MAX(forecast_week) AS max_week,
                   AVG(predicted_demand) AS avg_predicted_demand,
                   MIN(model_name) AS model_name,
                   MIN(model_version) AS model_version
            FROM forecast_results
            WHERE execution_id = %s
        """, (execution_id,))
        result = cursor.fetchone()
        return result or {}
    finally:
        cursor.close()
        if should_close and connection:
            connection.close()
